const removeDuplicates = (arr: string[]): string[] => {
  const uniqueItems: Record<string, boolean> = {};

  const uniqueArray = arr.filter((item) => {
    if (!uniqueItems[item]) {
      uniqueItems[item] = true;
      return true;
    }
    return false;
  });

  return uniqueArray;
};

export const cleanBenefits = removeDuplicates(benefits);

import { useState, useEffect } from "react";

export const useBenefits = () => {
  const [myBenefit, setMyBenefits] = useState([]);

  useEffect(() => {
    const fetchedBenefits = cleanBenefits;
    setMyBenefits(fetchedBenefits as []);
  }, [myBenefit]);

  return myBenefit;
};