"use client";
import { Payment} from "@prisma/client";
import { Printer } from "lucide-react";
import Link from "next/link";
import {
  Breadcrumb,
  BreadcrumbItem,
  BreadcrumbLink,
  BreadcrumbList,
  BreadcrumbPage,
  BreadcrumbSeparator,
} from "@/components/ui/breadcrumb";
import React, { useRef } from "react";
import { Button } from "@/components/ui/button";
import { useToast } from "@/components/ui/use-toast";
import Receipt from "./Receipt";
interface DisplayReceiptProps {
    receipt: Payment;
}

const DisplayReceipt = ({ receipt}: DisplayReceiptProps) => {
  const receiptRef = useRef<HTMLDivElement>(null);
  const { toast } = useToast();

  const isMobileDevice = () => {
    return /Mobi|Android/i.test(navigator.userAgent);
  };

  const handlePrint = () => {
    if (isMobileDevice()) {
      toast({
        title: "Print Functionality Unavailable",
        description: "Printing is not supported on mobile devices.",
        duration: 3000,
      });
      return;
    }

    const printContents = receiptRef.current?.innerHTML;
    const originalContents = document.body.innerHTML;

    if (printContents) {
      document.body.innerHTML = printContents;
      window.print();
      document.body.innerHTML = originalContents;
      window.location.reload();
    }
  };
  return (
    <div>
      <div className="flex items-center justify-between gap-x-3 flex-row mb-2">
        <Breadcrumb>
          <BreadcrumbList>
            <BreadcrumbItem>
              <BreadcrumbLink href="/manage/jobs">Home</BreadcrumbLink>
            </BreadcrumbItem>
            <BreadcrumbSeparator />
            <BreadcrumbItem>
              <BreadcrumbLink href="/manage/transactions">
                Payments
              </BreadcrumbLink>
            </BreadcrumbItem>
            <BreadcrumbSeparator />
            <BreadcrumbItem>
              <BreadcrumbPage>Receipt</BreadcrumbPage>
            </BreadcrumbItem>
          </BreadcrumbList>
        </Breadcrumb>
        <Button
          variant="default"
          onClick={handlePrint}
          type="button"
          className="hover:bg-primary h-[34px] w-[100px] hover:opacity-95"
          size="sm"
        >
          <Printer className="shrink-0 h-4 w-4 mr-1.5" />
          Print
        </Button>
      </div>
      <div className="flex sm:items-center sm:justify-center flex-row mb-1.5">
        <h3 className="font-bold text-gray-600 tracking-tight text-2xl sm:text-3xl">
          Payment Receipt
        </h3>
      </div>

      <div ref={receiptRef}>
        <Receipt receipt={receipt} />
      </div>

      <div className="mt-8 text-base">
        <span className="font-medium">Note: </span>This is an autogenerated
        receipt. Should you be having any concern about the content, kindly do
        not hesitate to{" "}
        <Link href="/manage/help" className="text-[#005580] font-medium">
          contact us
        </Link>
        .
      </div>
    </div>
  );
};

export default DisplayReceipt;
